// Extracts AyaSpell's whole-word replacements (anchored REP ^typo$ fix rules
// in dicts/ar/ar.aff, MPL 1.1, see dicts/ar/NOTICE) into the Arabic
// misspellings list, keeping only rules that pass the list checks and
// recording why each other rule was left out.
// Usage: npm run lists:ayaspell   (node --import ./eval/register.ts scripts/extract-ayaspell-rep.ts)
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { checkEntry, type ListEntry } from '../src/autocorrect/list-checks';
import { AYASPELL_NOT } from '../src/autocorrect/lists/ar';
import { stripMarks } from '../src/spell/arabic';
import { loadHunspell } from '../src/spell/engine';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const LIST_FILE = resolve(ROOT, 'src/autocorrect/lists/ar.ts');
const BEGIN = '// BEGIN AYASPELL';
const END = '// END AYASPELL';

/** Anchored whole-word rules of an .aff file, in file order. Hunspell writes a space in a REP target as "_". */
export function anchoredRules(affText: string): ListEntry[] {
  const rules: ListEntry[] = [];
  for (const line of affText.split(/\r?\n/)) {
    const m = /^REP\s+\^(\S+)\$\s+(\S+)\s*$/u.exec(line);
    if (m) rules.push({ typo: m[1], fix: m[2].replace(/_/g, ' ') });
  }
  return rules;
}

export interface Extracted {
  kept: ListEntry[];
  omitted: { entry: ListEntry; reasons: string[] }[];
}

/** typo → acknowledged spellings, from `typo<TAB>not: a b` lines. */
export function acknowledgements(text: string): Map<string, string[]> {
  const out = new Map<string, string[]>();
  for (const line of text.split(/\r?\n/)) {
    const m = /^(\S+)\tnot:\s*(.+)$/u.exec(line.trim());
    if (m) out.set(m[1], m[2].trim().split(/\s+/u));
  }
  return out;
}

/** Splits the rules into entries that pass the list checks and omissions with their reasons. */
export function extract(affText: string, isCorrect: (word: string) => boolean, acks = acknowledgements(AYASPELL_NOT)): Extracted {
  const result: Extracted = { kept: [], omitted: [] };
  for (const rule of anchoredRules(affText)) {
    const notPlausible = acks.get(rule.typo);
    const entry = notPlausible ? { ...rule, notPlausible } : rule;
    const reasons = checkEntry(entry, 'ar', isCorrect);
    if (reasons.length) result.omitted.push({ entry, reasons });
    else result.kept.push(entry);
  }
  return result;
}

/** The generated block of src/autocorrect/lists/ar.ts. */
export function renderBlock({ kept, omitted }: Extracted): string {
  return [
    `${BEGIN} (generated by scripts/extract-ayaspell-rep.ts; do not edit by hand)`,
    '// source: AyaSpell, dicts/ar/ar.aff, anchored whole-word REP rules',
    '// license: MPL 1.1 (tri-licensed upstream; see dicts/ar/NOTICE)',
    ...omitted.map(({ entry, reasons }) => `// left out: ${entry.typo} → ${entry.fix}: ${reasons.join('; ')}`),
    'export const AR_AYASPELL = `',
    ...kept.map((e) => `${e.typo}\t${e.fix}${e.notPlausible ? `\tnot: ${e.notPlausible.join(' ')}` : ''}`),
    '`;',
    END,
  ].join('\n');
}

/** The engine's correctness check for Arabic, as the worker answers it. */
export async function arabicIsCorrect(): Promise<(word: string) => boolean> {
  const rt = await loadHunspell({ wasmBinary: readFileSync(resolve(ROOT, 'src/spell/wasm/hunspell.wasm')) });
  const engine = rt.createEngine(readFileSync(resolve(ROOT, 'dicts/ar/ar.aff')), readFileSync(resolve(ROOT, 'dicts/ar/ar.dic')));
  return (w) => engine.spell(w) || (stripMarks(w) !== w && engine.spell(stripMarks(w)));
}

export const affText = () => readFileSync(resolve(ROOT, 'dicts/ar/ar.aff'), 'utf8');

/** The committed generated block, for the drift test. */
export function committedBlock(): string {
  const text = readFileSync(LIST_FILE, 'utf8');
  return text.slice(text.indexOf(BEGIN), text.indexOf(END) + END.length);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const result = extract(affText(), await arabicIsCorrect());
  const text = readFileSync(LIST_FILE, 'utf8');
  const start = text.indexOf(BEGIN);
  const end = text.indexOf(END);
  if (start < 0 || end < 0) throw new Error(`markers not found in ${LIST_FILE}`);
  writeFileSync(LIST_FILE, text.slice(0, start) + renderBlock(result) + text.slice(end + END.length));
  console.log(`kept ${result.kept.length}, left out ${result.omitted.length}`);
  for (const o of result.omitted) console.log(`  left out ${o.entry.typo} → ${o.entry.fix}: ${o.reasons.join('; ')}`);
}
